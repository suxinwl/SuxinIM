"""Synchronize build-time display names from clients/brand.json; IDs stay fixed."""
import argparse
import html
import hashlib
import json
import pathlib
import re

CLIENTS = pathlib.Path(__file__).resolve().parents[1]

def rendered_files(clients=CLIENTS):
    brand = json.loads((clients / 'brand.json').read_text(encoding='utf-8'))
    name, technical = brand['displayName'], brand['technicalName']
    if not isinstance(name, str) or name != name.strip() or not 1 <= len(name) <= 64 or any(ord(c) < 32 for c in name) or not isinstance(technical, str) or not re.fullmatch(r'[A-Za-z][A-Za-z0-9_]{0,47}', technical):
        raise ValueError('Invalid client brand configuration')
    web = clients / 'web-desktop'
    source_logo = clients / 'branding/IM.png'
    logo_version = hashlib.sha256(source_logo.read_bytes()).hexdigest()[:16] if source_logo.exists() else 'brand'
    outputs = {}
    index = web / 'index.html'
    outputs[index], count = re.subn(r'<title>[^<]*</title>', '<title>' + html.escape(name) + '</title>', index.read_text(encoding='utf-8'))
    if count != 1:
        raise ValueError('Expected one Web title')
    outputs[index] = re.sub(r'<link rel="icon"[^>]*>', '<link rel="icon" type="image/png" href="/favicon-32x32.png?v=' + logo_version + '" />', outputs[index])
    outputs[web / 'public/splash.html'] = '<!doctype html><html lang="zh-CN"><meta charset="utf-8"><title>' + html.escape(name) + '</title><style>html,body{margin:0;height:100%;background:#fff;font:15px sans-serif}body{display:flex;align-items:center;justify-content:center;text-align:center}img{width:88px;height:88px;object-fit:contain}p{margin:12px 0;color:#334155}</style><body><main><img src="./icons/icon.png?v=' + logo_version + '" alt=""><p>' + html.escape(name) + '</p></main></body></html>\n'
    builder_path = web / 'electron-builder.json5'
    builder = json.loads(builder_path.read_text(encoding='utf-8'))
    if builder['appId'] != 'io.openim.enterprise.upgrade38':
        raise ValueError('Existing Windows application identity changed')
    builder['productName'] = name
    builder['executableName'] = technical
    builder['win']['artifactName'] = technical + '-${version}-win-x64.${ext}'
    builder['nsis']['shortcutName'] = name
    builder['nsis']['uninstallDisplayName'] = name
    outputs[builder_path] = json.dumps(builder, ensure_ascii=False, indent=2) + '\n'
    dart = '// GENERATED by clients/tools/sync_brand.py from clients/brand.json.\n'
    dart += 'class AppBrand {\n'
    dart += '  static const displayName = ' + json.dumps(name, ensure_ascii=False).replace('$', r'\$') + ';\n'
    dart += '  static const technicalName = ' + json.dumps(technical) + ';\n'
    dart += "  static String nameFrom(Map<String, dynamic>? config) {\n    final value = config?['appName'];\n    return value is String && value.trim().isNotEmpty ? value.trim() : displayName;\n  }\n}\n"
    outputs[clients / 'flutter/openim_common/lib/src/brand.g.dart'] = dart
    plist = clients / 'flutter/ios/Runner/Info.plist'
    source = plist.read_text(encoding='utf-8')
    source, count = re.subn(r'(<key>CFBundleName</key>\s*<string>)[^<]*(</string>)', lambda match: match[1] + html.escape(name) + match[2], source)
    if count != 1:
        raise ValueError('Expected one iOS bundle name')
    if '<key>CFBundleDisplayName</key>' in source:
        source = re.sub(r'(<key>CFBundleDisplayName</key>\s*<string>)[^<]*(</string>)', lambda match: match[1] + html.escape(name) + match[2], source)
    else:
        source = source.replace('<key>CFBundleName</key>', '<key>CFBundleDisplayName</key>\n\t<string>' + html.escape(name) + '</string>\n\t<key>CFBundleName</key>')
    outputs[plist] = source
    return outputs

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    mismatches = []
    for path, content in rendered_files().items():
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            mismatches.append(str(path.relative_to(CLIENTS)))
            if not args.check:
                path.write_text(content, encoding='utf-8', newline='\n')
    if args.check and mismatches:
        raise SystemExit('Stale client brand outputs: ' + ', '.join(mismatches))
    print(json.dumps({'brandSynchronized': True, 'updated': 0 if args.check else len(mismatches)}, ensure_ascii=False))

if __name__ == '__main__':
    main()
